                                    <strong>Análisis de Suelo:</strong> Antes de instalar nuestros plantones frutales en campo es imprescindible contar con un análisis de suelo, porque nos brinda información muy importante y relevante como por ejemplo el pH que nos indica el nivel de solubilidad de los nutrientes o la conductividad eléctrica que nos indica el nivel de salinidad; esto último es de especial importancia sobre todo cuando trabajamos con paltos bajo condiciones de costa. Si el lector cuenta con un análisis de suelo y no sabe cómo interpretarlo o si desea obtener uno puede acudir a nosotros para que le brindemos una recomendación apropiada en base a los resultados obtenidos.</li>

                                    <li><strong>Preparación de terreno: </strong>Luego de interpretar los datos del análisis de suelo debemos continuar con la preparación del terreno. El objetivo general de esta etapa es que podamos brindar las mejores condiciones mecánicas del suelo para que la planta se pueda instalar y crecer con facilidad. Aquí removemos el terreno, preparamos los surcos o en algunos proyectos preparamos los camellones, todo esto para dar paso al hoyado en los cuales se colocarán los plantones.	A continuación mencionaremos los tres objetivos principales que buscamos en esta etapa: 
                                        <ul>
                                            <li><strong>Compactación:</strong> Se reﬁere a una capa dura presente en el perﬁl de nuestro suelo. Es importante identiﬁcarla y corregirla oportunamente porque esto evita que las raíces puedan crecer y explorar el suelo adecuadamente, además que reduce el nivel de inﬁltración del agua de riego lo que podría repercutir en una baja aireación en las raíces. Para veriﬁcar que nuestro suelo no esté compactado debemos realizar una calicata y analizar el perﬁl de suelo. Si tuviéramos alguna zona compactada debemos proceder a descompactar mecánicamente con un subsolador. Bajo condiciones de laderas o zonas de sierra en las cuales no puede llegar la maquinaria podemos hacer oriﬁcios de 80cm x 80cm x 80cm en cada posición en la que se realizará el trasplante. </li>
                                            <li><strong>Humedad:</strong>Antes de realizar cualquier labor debemos ablandar el terreno realizando un riego pesado y tendido. De esa manera activamos la actividad del suelo y a los pocos días facilita el trabajo de la maquinaria y de las personas</li>
                                            <li><strong>Aireación del suelo:</strong> Esto se logra removiendo el terreno en el cual se va a trabajar. Se puede hacer utilizando un arado de discos, en caso pueda hacerse mecánicamente,  o también utilizando un implemento jalado por un caballo.</li>                                                                                        
                                        </ul>
                                    </li>
 
