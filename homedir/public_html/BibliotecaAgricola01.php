                            <p>El trazado de una plantación consiste en establecer en campo la posición en la cual serán trasplantados los plantones. Esta distribución sigue la forma de algunas ﬁguras geométricas en las que cada vértice señala el punto exacto en el cual se colocará el plantón. Estas distancias se sustentan teniendo en consideración algunas características propias del cultivo y del manejo que se le dará tales como el tamaño ﬁnal de los árboles, el nivel de mecanización en las operaciones agrícolas, las curvas de nivel y sistemas de riego, entre otras. A partir de tener establecido el trazo de plantación podemos calcular el número de plantas que necesitaremos por hectárea. El producto de la distancia entre plantas y entre ﬁlas se conoce como <strong>“densidad de planta ción”</strong>.
                            </p>                         
                            <p>En general podríamos considerar que la distancia mínima recomendable entre plantas para palto es de 4 metros y para mango es de 3 metros. Toda plantación que se realice a una distancia menor podría ser considerada como un sistema de plantación a alta densidad.
                            </p>                             
