                            <p>Antes de realizar la instalación de una plantación de árboles frutales debemos comenzar con una adecuada selección de plantones de la mejor calidad porque nuestra inversión es a largo plazo y necesitamos hacer las cosas de manera óptima desde el principio para asegurar el aprovechamiento del máximo potencial de nuestro cultivo. Para conseguir los plantones de frutales normalmente nos dirigimos a un vivero de nuestra localidad pero nuestra limitación es que no conocemos el historial de vivero de las plantas que estamos por comprar. Por ello, a continuación brindamos algunas recomendaciones para realizar una mejor selección antes de la compra :
                            </p>

                               <ul style="list-style-type: square;">
                                   
                                    <div style="padding:0; width:100%;">
                                        <img id="imgprincipal" src="imgs/BibliotecaAgricola/materialgvegetal.jpg" alt="Biblioteca Agricola" style="width: 500px; padding: 10px;float: right;">
                                    </div>
                                    <li>
                                    <strong>Tipo de contenedor:</strong> Nos referimos a la bolsa que contiene al plantón. Es importante que esta sea de buena calidad, altura y ancho porque si tenemos en cuenta el rápido crecimiento de raíces y tiempo que permanecerá en vivero es importante que este sea de buen tamaño <strong>“mientras más grande, mejor”</strong>. En ocasiones muchos clientes preﬁeren bolsas pequeñas porque facilita el transporte. Para este caso es recomendable que las plantas no estén injertadas pero que cuenten a lo más con el segundo ﬂujo de crecimiento establecido. En cuanto a las características de las bolsas recomendamos para plantones de frutales como el palto, mango, lúcumo y otros, tengan un grosor de al menos 3 micras, altura mínima de 15 pulgadas y ancho de 7 pulgadas. Para asegurar una buena oxigenación y drenaje del agua de las bolsas es importante que tengan oriﬁcios en la base para una adecuada evacuación del exceso de agua.</li>
                                    <li><strong>Edad:</strong> Para asegurar plantones de calidad es muy importante que el tiempo que hayan permanecido en bolsas sea el menor posible. Para plantones injertados recomendamos que no sea más de 12 meses. La principal razón es porque luego de permanecer un año en bolsa es muy probable que la raíz principal en su crecimiento haya llegado hasta la base de la bolsa y al no poder continuar con su crecimiento tiende a enrollarse sobre sí misma, efecto que se conoce como <strong>“raíz sentada”</strong>. Las plantas que se instalan en campo deﬁnitivo con este problema suelen tener un crecimiento lento y son susceptibles a enfermedades, no producen adecuadamente y luego de algunos años mueren.</li>

                                    <li><strong>Eje principal:</strong> Debemos veriﬁcar que el plantón tenga un solo eje de crecimiento sano y vigoroso, signiﬁca que desde el cuello de la planta hasta el ápice no debe haber evidencia que brotes muertos que hayan sido reemplazados por otros.</li>
                              </ul>
                              
                              
