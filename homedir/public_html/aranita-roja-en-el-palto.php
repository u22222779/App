                            <p class="notitex es">Los ácaros fitófagos, que son aquellos que se alimentan de material vegetal, son comúnmente llamados “arañitas rojas”. Estos ácaros son polífagos, a tal punto que se desarrollan de forma óptima en más de 150 especies vegetales y pueden afectar, en menor grado, prácticamente a todos los cultivos.</p>

<div><img id="imgprincipal" src="imgs/aranita-roja-en-elpalto.jpg" alt=""></div>
<p class="notitex es">                    
La especie principal de “arañita roja” que afecta el cultivo del palto es la Oligonychus punicae Hirst, lal cual es también conocida como “arañita marrón del palto”. Dentro de los diferentes cultivos comerciales del palto, se ha visto que ˈHassˈ es el más susceptible a la arañita marrón del palto, causando consecuencias directas sobre la calidad de la fruta y disminución del rendimiento; en tal sentido, el manejo de este ácaro es muy importante para obtener buenos rendimientos, tomando en cuenta la apertura de mercados internacionales que reconocen la calidad de la palta peruana y que exigen cada vez mayores volúmenes de producción.</p>
<div><img id="imgprincipal" src="imgs/aranita-roja-en-elpalto2.jpg" alt=""></div>                  
<strong class="notitit">CONDICIONES FAVORABLES</strong>
<p class="notitex">
Los ácaros, como Oligonychus punicae, prefieren condiciones de alta temperatura y baja humedad relativa. Bajo estas condiciones reducen el número de días que requiere para completar su ciclo de vida por lo que se tendrá mayor cantidad de generaciones de ácaros en menor tiempo. Sumado a ello, se facilita su desarrollo en hojas que contengan suciedad y polvo, plantas deshidratadas, estresadas y/o enfermas, pues, debido a la capa de suciedad, el control se ve entorpecido, porque los productos químicos se fijan en las arcillas del polvo sin llegar a afectar al patógeno en cuestión.</p>

<strong class="notitit">DAÑOS</strong>
<p class="notitex">   
Estos ácaros se desarrollan principalmente en las hojas maduras cerca a las nervaduras, alimentándose, tanto los estadios inmaduros como adultos, del contenido de las células superficiales de la hoja. Por lo general, las hojas infestadas se caen prematuramente debido al rompimiento de las células, la remoción de la clorofila y la saliva inyectada por los ácaros lleva al mal funcionamiento de la hoja, como el aumento en la tasa de transpiración, que resulta en su marchitez y caída temprana. En ataques severos por alta densidad de la plaga puede invadir follaje nuevo en expansión, ocasionando defoliación parcial en el árbol, bajo calibre de la fruta y caída del fruto joven recién formado.</p>
<div><img id="imgprincipal" src="imgs/aranita-roja-en-elpalto3.jpg" alt=""></div>  
