<strong class="notitit">MEDIDAS DE CONTROL</strong>                    
<p class="notitex">                    
Los dos primeros pasos para realizar una medida de control son la prevención y evaluación. La primera se logra evitando condiciones que favorezcan la instalación del ácaro, como el mantenimiento de hojas limpias sin polvo, planta bien nutrida e hidratada; las evaluaciones se deben realizar semanalmente, constatando la presencia de los ácaros. Si se observa presencia de ácaros en niveles de entre 1 – 5 individuos por hoja debemos realizar alguna medida de control como por ejemplo:</p>
<p class="notitex">
Lavados: Agua con detergente agrícola (no usar detergente de ropa y mucho menos con lejía), incluso se podrían realizar los lavados usando solo agua limpia.
Sulfocalcio: Preferentemente a dosis de 5 litros/cilindro
Acaricidas: Azufre, Abamectina, Fenpiroximate, Spirodiclofen, Etoxazole, entre otros.</p>
<p class="notitex">
Recordemos que ningún agroquímico regula los huevos de los ácaros, por ello para controlarlos de manera más eficiente se deben realizar dos aplicaciones separadas entre 5 – 7 días con productos de diferente ingrediente activo.</p>
                    


              
