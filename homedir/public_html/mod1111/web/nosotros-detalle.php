                            <h1>
                                <strong class="notitit es">Misión</strong>
                                <strong class="notitit en" style="display:none;">Unsere Mission</strong>
                                <strong class="notitit de" style="display:none;">Unsere Mission</strong>
                            </h1>
                            <p class="notitex es">SEDIR, promueve el desarrollo de los conocimientos y las tecnologías de práctica agrícola de los productores del distrito de Moro orientado a obtener un mayor beneficio mediante un uso responsable de los recursos de explotación.</p>
                            <p class="notitex en" style="display:none;">SEDIR, promotes the development of knowledge and technologies of agricultural practice of producers of oriented Moro district to obtain a greater benefit by a responsible use of resources exploitation.</p>
                            <p class="notitex de" style="display:none;">SEDIR foerdert die Entwicklung von Wissen und von Technologien in der landwirtschaftlichen Praxis der Bauern im Einzugsbereich von Moro und ist darauf ausgerichtet, durch schonende Nutzung der langfristig zur Verfuegung stehenden natuerlichen Ressourcen einen Mehrwert zu erzielen.</p>                            
                        </article>

