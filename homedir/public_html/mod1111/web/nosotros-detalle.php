                                 <strong class="notitit es">Quienes Somos</strong>
                                 <strong class="notitit en" style="display:none;">About Us</strong>
                                 <strong class="notitit de" style="display:none;">Institutionelle Beschreibung</strong>
                            </h1>
                            <p class="notitex es">SEDIR es una organización dedicada a las actividades de desarrollo agrícola, pecuario y agroindustrial en el distrito de Moro y el valle Nepeña.  Las acciones específicas se concentran en la implementación de programas de desarrollo de capacidades a productores y técnicos en el campo agropecuario; así mismo, la transferencia de tecnología mediante la asistencia técnica. En el campo agroindustrial promovemos el valor agregado a los productos agrícolas, la agroexportación, desarrollo de nuevos productos, apoyo a las MYPE y el fortalecimiento de marcas locales.</p>
                            <p class="notitex en" style="display:none;">SEDIR, is an organization dedicated to agriculture, livestock and agro-industrial development in the district of Moro and Nepeña valley. The activities are focused on the implementation of building programs to producers and technicians in the agricultural field, and the transfer of technology through technical assistance. In the agribusiness field, to promote the value added to agricultural, exportation through the development of new products, support MSEs and strengthening of local brands.</p>
                            <p class="notitex de" style="display:none;">SEDIR ist eine Organisation, die sich den Aktivitaeten im Ackerbau, in der Viehzucht und der agroindustriellen Entwicklung im Bezirk Moro und dem Nepeñatal widmet. Spezifische Maßnahmen konzentrieren sich auf die Umsetzung von Aus- und Weiterbildungsprogrammen von Bauern und der Agrartechniker, aber auch dem Transfer von Technologie durch technische Assistenz. Der Wert der Agroindustrie soll durch die Entwicklung neuer landwirtschaftlicher Produkte, durch die Foerderung agrarischer Exportprodukte, durch Unterstuetzung von Kleinunternehmen und durch die Staerkung regionaler Marken gesteigert werden.</p>                            
                        </article>

