                                <strong class="notitit es">Visión</strong>
                                <strong class="notitit en" style="display:none;">Vision</strong>
                                <strong class="notitit de" style="display:none;">Unsere Vision</strong>
                            </h1>
                            <p class="notitex es">La zona de influencia de SEDIR ha desarrollado plenamente una agricultura autosustentable con altos estándares de calidad de productos, tecnologías de producción, asociatividad, acceso al mercado y responsabilidad social, generando de esta manera una mejora de la calidad de vida de las familias.</p>
