                            <p class="notitex">La intervención en la Sub Cuenca del Río Loco (1,300 a 4,000 m.s.n.m) involucra a 16 caseríos: Cajay, Huanchuy, Cápan, Carachuco, Cárap, Pichiu, Carampa, Pampa Cancha, Huarac Hurán, Huáscar, Pisha, Quicacayán, Pucará, Antaracá, Ocshapampa, Nununga.
                            En ésta zona hay una diferenciación de ecosistemas debido a la variación de microclimas. La altitud es un factor que define la diversidad de cultivos que se desarrollan. 
                            </p>
                           
                            <strong class="notitit" style="padding-left:30px;">Capacitación a productores campesinos</strong>
                            <p style="padding-left:30px;">
                            <span class="notitex">
                            El grupo objetivo de ésta actividad son los productores campesinos de los 16 caseríos ubicados en la vertiente del Río Loco.
                            En gran parte de estos lugares la práctica de la agricultura es con fines de autoconsumo y debido a la variación de microclimas podemos encontrar condiciones para el desarrollo de cultivos diversos, pero sobre estructuras limitadas, como es: la frontera agrícola, fuente e infraestructura de riego.
                            </span>
